import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const rootDir = path.resolve(__dirname, '..');
const srcDir = path.join(rootDir, 'Certificates');
const destDir = path.join(rootDir, 'public', 'certificates');

function copyFolderRecursiveSync(source, target) {
  if (!fs.existsSync(target)) {
    fs.mkdirSync(target, { recursive: true });
  }

  if (fs.lstatSync(source).isDirectory()) {
    const files = fs.readdirSync(source);
    files.forEach((file) => {
      const curSource = path.join(source, file);
      const curTarget = path.join(target, file);
      if (fs.lstatSync(curSource).isDirectory()) {
        copyFolderRecursiveSync(curSource, curTarget);
      } else {
        fs.copyFileSync(curSource, curTarget);
      }
    });
  }
}

console.log('Copying certificates to public/certificates...');

if (fs.existsSync(srcDir)) {
  copyFolderRecursiveSync(srcDir, destDir);
  console.log('Successfully copied domain certificates hierarchy to public/certificates.');
} else {
  console.warn(`Warning: Source directory not found: ${srcDir}`);
}
